pub fn generate(repo_root: &Path) -> Result<()> {
    let generated_files = all_generated_files(repo_root)?;
    crate::protocol_generate::remove_obsolete(repo_root, &generated_files)?;
    for obsolete in crate::phase02_generate::unexpected_files(repo_root, &generated_files)? {
        fs::remove_file(repo_root.join(&obsolete))
            .with_context(|| format!("failed to remove obsolete generated pack file {obsolete}"))?;
    }
    for (relative_path, contents) in &generated_files {
        let path = repo_root.join(relative_path);
        let parent = path
            .parent()
            .with_context(|| format!("generated path has no parent: {}", path.display()))?;
        fs::create_dir_all(parent)
            .with_context(|| format!("failed to create {}", parent.display()))?;

        if fs::read(&path).ok().as_deref() != Some(contents.as_slice()) {
            fs::write(&path, contents)
                .with_context(|| format!("failed to write {}", path.display()))?;
        }
    }

    println!("generated {} file(s)", generated_files.len());
    Ok(())
}

pub fn check(repo_root: &Path) -> Result<()> {
    let generated_files = all_generated_files(repo_root)?;
    crate::protocol_generate::reject_unexpected(repo_root, &generated_files)?;
    let unexpected = crate::phase02_generate::unexpected_files(repo_root, &generated_files)?;
    ensure!(
        unexpected.is_empty(),
        "generated pack inventory contains unowned files: {}",
        unexpected.join(", ")
    );
    let mut drifted = Vec::new();

    for (relative_path, expected) in &generated_files {
        let path = repo_root.join(relative_path);
        match fs::read(&path) {
            Ok(actual) if actual == expected.as_slice() => {}
            Ok(_) | Err(_) => drifted.push(relative_path.as_str()),
        }
    }

    if !drifted.is_empty() {
        bail!(
            "generated files are missing or stale: {}; run `cargo xtask generate`",
            drifted.join(", ")
        );
    }

    println!("checked {} generated file(s)", generated_files.len());
    Ok(())
}

fn generated_files() -> Vec<(&'static str, String)> {
    vec![
        (GENERATED_DESKTOP_API_PATH, generated_desktop_api()),
        (
            GENERATED_RUST_COMMAND_CATALOG_PATH,
            generated_rust_command_catalog(),
        ),
    ]
}

fn all_generated_files(repo_root: &Path) -> Result<Vec<crate::protocol_generate::GeneratedOutput>> {
    let mut files = generated_files()
        .into_iter()
        .map(|(path, contents)| (path.to_owned(), contents.into_bytes()))
        .collect::<Vec<_>>();
    files.extend(
        crate::phase02_generate::generated_files(repo_root)?
            .into_iter()
            .map(|(path, contents)| (path.to_owned(), contents.into_bytes())),
    );
    files.push(crate::source_contract::generated_file(repo_root)?);
    files.push(crate::source_contract::dependency_sources_generated_file()?);
    files.extend(crate::protocol_generate::generated_files(repo_root)?);
    files.sort_by(|left, right| left.0.cmp(&right.0));
    ensure_unique_generated_paths(&files)?;
    Ok(files)
}

fn ensure_unique_generated_paths(
    files: &[crate::protocol_generate::GeneratedOutput],
) -> Result<()> {
    for pair in files.windows(2) {
        ensure!(
            pair[0].0 != pair[1].0,
            "generated path is owned by more than one generator: {}",
            pair[0].0
        );
    }
    Ok(())
}

